import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {createInterface} from 'node:readline';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'.validation','member-nickname-ui-20261023');
await fs.mkdir(output,{recursive:true});
const fixture=spawn('python',['-B',path.join(root,'deployments/raksmart-198.200.49.63/serve_access_records_demo.py')],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
const lines=createInterface({input:fixture.stdout});
let startupTimer;
const first=await Promise.race([new Promise((resolve,reject)=>{lines.once('line',resolve);fixture.once('exit',()=>reject(new Error('Fixture exited')));}),new Promise((_,reject)=>{startupTimer=setTimeout(()=>reject(new Error('Fixture startup timeout')),20000);})]);
clearTimeout(startupTimer);
const origin=JSON.parse(first).origin;
const report={success:false,checks:[],errors:[],production_changed:false,synthetic_data:true};
const check=name=>report.checks.push(name);
let browser;
async function login(page,username,password) {
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.locator('#login-user').fill(username);await page.locator('#login-password').fill(password);
  await page.locator('#login-submit').click();await page.locator('#console').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#metric-server').textContent!=='—');
}
try {
  browser=await chromium.launch({channel:'msedge',headless:true});
  const adminContext=await browser.newContext({viewport:{width:1440,height:1000}});
  const memberContext=await browser.newContext({viewport:{width:390,height:844}});
  const page=await adminContext.newPage(),member=await memberContext.newPage();
  for(const surface of [page,member]) surface.on('pageerror',error=>report.errors.push(error.message));
  await login(page,'admin','demo-password-2026');
  await login(member,'member_alpha','synthetic-browser-password-2026');
  await page.locator('#users-nav').click();
  const cards=page.locator('.user-card');
  await cards.nth(2).waitFor();
  const target=cards.filter({has:page.locator('.user-username',{hasText:'member_alpha'})});
  assert.equal(await cards.locator('[data-user-action=nickname]:visible').count(),2);
  check('administrator sees nickname actions for members');
  const original=await target.locator('.user-display-name').textContent();
  await target.locator('[data-user-action=nickname]').click();
  assert.equal(await page.locator('#nickname-value').inputValue(),original);
  assert.equal(await page.locator('#nickname-username').inputValue(),'member_alpha');
  assert.equal(await page.locator('#nickname-username').evaluate(element=>element.readOnly),true);
  await page.locator('#nickname-value').fill('取消的昵称');await page.locator('#cancel-user-nickname').click();
  assert.equal(await target.locator('.user-display-name').textContent(),original);
  check('prefilled nickname, stable username and cancel without saving');
  await target.locator('[data-user-action=nickname]').click();
  await page.locator('#nickname-value').fill('   ');await page.locator('#save-user-nickname').click();
  await page.locator('#nickname-error').filter({hasText:'昵称需要'}).waitFor();
  assert.equal(await page.locator('#user-nickname-dialog').isVisible(),true);
  check('blank nickname remains in editor with a validation message');
  const nickname='小张 · 办公电脑 <b>测试</b>';
  await page.locator('#nickname-value').fill('  '+nickname+'  ');
  await page.locator('#save-user-nickname').click();
  await page.locator('#user-nickname-dialog').waitFor({state:'hidden'});
  assert.equal(await target.locator('.user-display-name').textContent(),nickname);
  assert.equal(await target.locator('.user-display-name b').count(),0);
  check('save trims nickname and renders markup as plain text');
  await member.reload({waitUntil:'networkidle'});
  await member.locator('#console').waitFor({state:'visible'});
  assert.equal(await member.locator('#current-user-name').textContent(),nickname);
  assert.equal(await member.locator('#users-nav').isVisible(),false);
  const denial=await member.evaluate(async()=>{
    const session=await(await fetch('./api/session')).json();
    return(await fetch('./api/users/nickname',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':session.csrf},body:JSON.stringify({id:session.user.id,display_name:'自助修改'})})).status;
  });
  assert.equal(denial,403);
  check('existing member session displays new nickname while editing remains admin-only');
  await target.locator('[data-user-action=visits]').click();
  await page.waitForFunction(()=>document.querySelector('#visits-member').selectedOptions[0].textContent.includes('小张'));
  assert.match(await page.locator('#visits-rows tr').first().textContent(),/小张/);
  assert.equal(await page.locator('#visits-rows b').count(),0);
  check('historical access rows and member filter display the current nickname');
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#console').waitFor({state:'visible'});await page.locator('#users-nav').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('.user-display-name')].some(element=>element.textContent.includes('小张')));
  await page.locator('#member-search').fill('小张');
  assert.equal(await cards.filter({visible:true}).count(),1);
  check('nickname persists after refresh and can be searched');
  await target.locator('[data-user-action=nickname]').click();
  await page.screenshot({path:path.join(output,'nickname-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(output,'nickname-mobile.png'),fullPage:true});
  await page.locator('#nickname-value').fill('临时输入');await page.keyboard.press('Escape');
  assert.equal(await page.locator('#user-nickname-dialog').isVisible(),false);
  assert.equal(await target.locator('.user-display-name').textContent(),nickname);
  check('mobile editor fits the screen and Escape cancels edits');
  await page.locator('#logout-mobile').click();await page.locator('#login-screen').waitFor({state:'visible'});
  assert.equal(await page.locator('#nickname-value').inputValue(),'');
  assert.equal(await page.locator('#nickname-user-id').inputValue(),'');
  check('logout clears nickname editor fields');
  assert.deepEqual(report.errors,[]);report.success=true;
}catch(error){report.failure_type=error.name;report.failure=error.message;}
finally{
  await browser?.close();fixture.kill();lines.close();
  await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2));
  process.stdout.write(JSON.stringify({success:report.success,checks:report.checks.length,report:path.join(output,'report.json'),failure:report.failure})+'\n');
}
process.exitCode=report.success?0:1;

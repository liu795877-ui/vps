import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {createInterface} from 'node:readline';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output = path.join(root,'.validation','member-access-ui-20261023');
await fs.mkdir(output,{recursive:true});
const fixture = spawn('python',['-B',path.join(root,'deployments/raksmart-198.200.49.63/serve_access_records_demo.py')],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
const lines = createInterface({input:fixture.stdout});
let startupTimer;
const first = await Promise.race([new Promise((resolve,reject) => {lines.once('line',resolve);fixture.once('exit',() => reject(new Error('Fixture exited')));}),new Promise((_,reject) => {startupTimer=setTimeout(() => reject(new Error('Fixture startup timeout')),20000);})]);
clearTimeout(startupTimer);
const origin = JSON.parse(first).origin;
const report = {success:false,checks:[],errors:[],production_changed:false,synthetic_data:true};
let browser;
const check = name => report.checks.push(name);
async function login(page,username,password) {
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.locator('#login-user').fill(username);await page.locator('#login-password').fill(password);
  await page.locator('#login-submit').click();await page.locator('#console').waitFor({state:'visible'});
  await page.waitForFunction(() => document.querySelector('#metric-server').textContent!=='—');
}
try {
  browser = await chromium.launch({channel:'msedge',headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Los_Angeles'});
  const page = await context.newPage();
  page.on('pageerror',error => report.errors.push(error.message));
  const stylesheet = await context.request.get(new URL('/access-records.css',origin).href);
  assert.equal(stylesheet.status(),200);
  assert.match(stylesheet.headers()['content-type'],/text\/css/);
  check('access records stylesheet is served successfully');
  await login(page,'admin','demo-password-2026');
  await page.locator('#visits-nav').click();
  await page.waitForFunction(() => document.querySelector('#visits-total').textContent==='65');
  assert.equal(await page.locator('#visits-rows tr').count(),50);
  assert.equal(await page.locator('#visits-members').textContent(),'2');
  assert.match(await page.locator('#visits-timezone').textContent(),/America\/Los_Angeles/);
  check('administrator summary, first page and browser time zone');
  assert.equal(await page.locator('#visits-rows b').count(),0);
  assert.equal((await page.locator('#view-visits').textContent()).includes('owner-private.example'),false);
  check('owner connections excluded and member labels rendered as text');
  await page.locator('#visits-next').click();
  await page.waitForFunction(() => document.querySelector('#visits-page').textContent.includes('2 / 2'));
  assert.equal(await page.locator('#visits-rows tr').count(),15);
  check('stable pagination and total count');
  const members = await page.evaluate(async () => (await (await fetch('./api/access-records')).json()).members);
  const beta = members.find(member => member.username==='member_beta');
  await page.locator('#visits-member').selectOption(beta.id);
  await page.waitForFunction(() => document.querySelector('#visits-total').textContent==='8');
  assert.equal(await page.locator('#visits-rows tr').count(),8);
  assert.match(await page.locator('#visits-popular').textContent(),/beta.example/);
  check('member filter and matching destination aggregate');
  await page.locator('#visits-member').selectOption('');
  await page.locator('#visits-protocol').selectOption('reality');
  await page.waitForFunction(() => document.querySelector('#visits-total').textContent==='28');
  assert.equal(await page.locator('#visits-rows .hy2').count(),0);
  check('protocol filter');
  await page.locator('#visits-query').fill('nothing.example');await page.locator('#visits-filter-form button[type=submit]').click();
  await page.locator('#visits-empty').waitFor({state:'visible'});
  assert.equal(await page.locator('#visits-total').textContent(),'0');
  check('domain search and empty state');
  await page.locator('#visits-query').fill('');await page.locator('#visits-protocol').selectOption('');
  await page.waitForFunction(() => document.querySelector('#visits-total').textContent==='65');
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:path.join(output,'administrator-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:path.join(output,'administrator-mobile.png'),fullPage:true});
  report.mobile_layout = await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth,overflow:[...document.querySelectorAll('body *')].filter(e => !e.closest('[hidden]') && e.getBoundingClientRect().right>innerWidth+1).slice(0,12).map(e => ({tag:e.tagName,id:e.id,class:e.className,width:e.getBoundingClientRect().width,right:e.getBoundingClientRect().right}))}));
  assert.equal(report.mobile_layout.scroll<=report.mobile_layout.width,true);
  check('desktop and mobile layout without page overflow');
  await page.locator('#logout-mobile').click();await page.locator('#login-screen').waitFor({state:'visible'});
  assert.equal(await page.locator('#visits-rows tr').count(),0);
  assert.equal(await page.locator('#visits-popular li').count(),0);
  check('logout removes member records from the DOM');
  await login(page,'member_alpha','synthetic-browser-password-2026');
  assert.equal(await page.locator('#visits-nav').isVisible(),false);
  const denied = await page.evaluate(async () => (await fetch('./api/access-records')).status);
  assert.equal(denied,403);
  assert.equal(await page.locator('#visits-rows tr').count(),0);
  check('member has no navigation, API access or retained administrator data');
  assert.deepEqual(report.errors,[]);report.success=true;
} catch (error) {report.failure_type=error.name;report.failure=error.message;}
finally {
  await browser?.close();fixture.kill();lines.close();
  await fs.writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2));
  process.stdout.write(JSON.stringify({success:report.success,checks:report.checks.length,report:path.join(output,'report.json'),failure:report.failure})+'\n');
}
process.exitCode=report.success ? 0 : 1;
